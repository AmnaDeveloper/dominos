/**
 * Generates honest placeholder graphics for menu item pages.
 *
 * These are deliberately typographic cards, NOT stock food photos and NOT a
 * photo of a different item. Putting a pizza photo on a pasta page would be
 * misleading to readers and reads as low-effort to reviewers. Replace these
 * with real photographs of actual orders when you have them — that is a real
 * quality upgrade, and these are only a truthful stand-in until then.
 *
 *   node scripts/generate-menu-images.mjs
 */
import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.join(process.cwd(), "public", "menu");

// Domino's-inspired palette from src/lib/site-config.ts
const NAVY = "#003F5C";
const BLUE = "#006491";
const RED = "#E31837";

const ITEMS = [
  ["chicken-alfredo-pasta", "Chicken Alfredo", "Pasta"],
  ["italian-sausage-marinara-pasta", "Italian Sausage Marinara", "Pasta"],
  ["pasta-primavera", "Pasta Primavera", "Pasta"],
  ["philly-cheese-steak-sandwich", "Philly Cheese Steak", "Sandwich"],
  ["chicken-bacon-ranch-sandwich", "Chicken Bacon Ranch", "Sandwich"],
  ["mediterranean-veggie-sandwich", "Mediterranean Veggie", "Sandwich"],
  ["chocolate-lava-crunch-cakes", "Lava Crunch Cakes", "Dessert"],
  ["cinnamon-bread-twists", "Cinnamon Bread Twists", "Dessert"],
  ["marbled-cookie-brownie", "Marbled Cookie Brownie", "Dessert"],
  ["parmesan-bread-bites", "Parmesan Bread Bites", "Sides & Bread"],
  ["garlic-bread-twists", "Garlic Bread Twists", "Sides & Bread"],
  ["loaded-tots", "Loaded Tots", "Sides & Bread"],
];

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** Wrap a title onto at most two lines so long names stay readable. */
function lines(title) {
  const words = title.split(" ");
  if (words.length < 3) return [title];
  const mid = Math.ceil(words.length / 2);
  return [words.slice(0, mid).join(" "), words.slice(mid).join(" ")];
}

const card = (title, category) => {
  const ls = lines(title);
  const startY = ls.length === 1 ? 330 : 292;
  const tspans = ls
    .map((l, i) => `<tspan x="600" y="${startY + i * 76}">${esc(l)}</tspan>`)
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="675">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="${BLUE}"/>
      <stop offset="100%" stop-color="${NAVY}"/>
    </linearGradient>
  </defs>
  <rect width="1200" height="675" fill="url(#g)"/>
  <rect x="0" y="0" width="1200" height="10" fill="${RED}"/>
  <text x="600" y="212" text-anchor="middle" fill="#ffffff" fill-opacity="0.72"
        font-family="Helvetica, Arial, sans-serif" font-size="30" font-weight="700"
        letter-spacing="7">${esc(category.toUpperCase())}</text>
  <text text-anchor="middle" fill="#ffffff"
        font-family="Helvetica, Arial, sans-serif" font-size="66" font-weight="800">${tspans}</text>
  <rect x="530" y="${startY + ls.length * 76 - 6}" width="140" height="6" fill="${RED}"/>
  <text x="600" y="${startY + ls.length * 76 + 74}" text-anchor="middle" fill="#ffffff" fill-opacity="0.62"
        font-family="Helvetica, Arial, sans-serif" font-size="25">Unofficial menu guide — illustration, not a product photo</text>
</svg>`;
};

async function run() {
  await mkdir(OUT, { recursive: true });
  for (const [slug, title, category] of ITEMS) {
    const svg = Buffer.from(card(title, category));
    await sharp(svg).webp({ quality: 82 }).toFile(path.join(OUT, `${slug}.webp`));
    console.log("wrote public/menu/" + slug + ".webp");
  }
  await writeFile(
    path.join(OUT, "README.txt"),
    "Generated by scripts/generate-menu-images.mjs.\n" +
      "These are typographic placeholders, not photographs. Replace them with real\n" +
      "photos of actual orders when available, then delete this file.\n"
  );
}

run().catch((e) => {
  console.error(e);
  process.exit(1);
});
